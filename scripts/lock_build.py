"""Regenerate .github/requirements/build.txt: hash-pinned release tooling for CI (Linux, Python 3.12).

Usage: python scripts/lock_build.py   (needs network access to pypi.org)
"""
from __future__ import annotations

import json
import re
import subprocess
import sys
import tempfile
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOP = ["build==1.6.1", "twine==7.0.0", "setuptools==84.1.0"]


def main() -> None:
    with tempfile.TemporaryDirectory() as tmp:
        report = Path(tmp) / "report.json"
        subprocess.run([sys.executable, "-m", "pip", "install", "--dry-run", "--ignore-installed", "--quiet", "--isolated",
                        "--report", str(report), "--only-binary=:all:", "--target", str(Path(tmp) / "t"),
                        "--python-version", "3.12", "--implementation", "cp",
                        "--platform", "manylinux_2_28_x86_64", "--platform", "manylinux2014_x86_64", *TOP], check=True)
        items = json.loads(report.read_text())["install"]
    lines = ["# Generated by scripts/lock_build.py. Do not edit.",
             "# Release tooling for .github/workflows/publish.yml; installed with pip --require-hashes."]
    for name, version in sorted({(re.sub(r"[-_.]+", "-", i["metadata"]["name"]).lower(), i["metadata"]["version"]) for i in items}):
        with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=60) as response:
            urls = json.load(response)["urls"]
        hashes = sorted({u["digests"]["sha256"] for u in urls if u["packagetype"] == "bdist_wheel"})
        if not hashes:
            raise SystemExit(f"{name} {version} has no wheels")
        lines.append(f"{name}=={version} " + " ".join(f"\\\n    --hash=sha256:{h}" for h in hashes))
    (ROOT / ".github" / "requirements" / "build.txt").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
